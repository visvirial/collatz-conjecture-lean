#!/usr/bin/env python3
"""Generate the incremental extension of the CollatzBig verification.

The existing chunks (`CollatzBig/Res*.lean`, `resCheck K M0 FUEL`, K = J0 + D) prove descent of
every 2 <= n < 2^K * M0 and are reused unchanged. This script writes

  * Ext####.lean:   `kallFrom (resExt J0 D M0 M1 FUEL) lo len = true` over top-level residues
                    r < 2^J0 (Collatz/ExtDefs.lean), cost-balanced from the plan_ext output;
  * ExtCyc###.lean: `kallFrom (cycCheck2 N) lo len = true`, N = 2^K * M1, for b < B, where B is
                    the first b at which cycCheck2 N b fails;
  * Ext.lean:       balanced trees of `kallFrom_append` and the final theorems
                    (namespace CollatzBig.Ext);
  * ExtAudit.lean:  axiom check of the final theorems;
  * ext_queue.txt:  the chunk module names, one per line (a queue for scripts/distributed/worker.sh).

Usage:
  gen_ext.py J0 D M0 M1 FUEL plan.txt OUTDIR [--cost C] [--cyc-chunks CC]
             [--cert-w W] [--m-w W] [--node-w W] [--only NAME,NAME,...]
plan.txt is the stdout of scripts/plan_ext.c with the same J0 D M0 M1 FUEL
(`r certIters leaves steps maxsteps` per top-level residue). Chunk files go to OUTDIR
(e.g. CollatzBig/); with --only, only the listed chunk modules are written.
"""
import argparse
import os

ap = argparse.ArgumentParser()
for a in ("J0", "D", "M0", "M1", "FUEL"):
    ap.add_argument(a, type=int)
ap.add_argument("plan")
ap.add_argument("outdir")
ap.add_argument("--cost", type=int, default=850000, help="target cost per residue chunk")
ap.add_argument("--cyc-chunks", type=int, default=20)
ap.add_argument("--cert-w", type=int, default=6, help="cost of one certAux iteration")
ap.add_argument("--m-w", type=int, default=20, help="overhead per checked n (leaf x m)")
ap.add_argument("--node-w", type=int, default=10, help="overhead per top-level residue")
ap.add_argument("--only", default=None)
args = ap.parse_args()

J0, D, M0, M1, FUEL = args.J0, args.D, args.M0, args.M1, args.FUEL
K = J0 + D
R0 = 2 ** J0
N0 = 2 ** K * M0
N = 2 ** K * M1
assert 1 <= M0 < M1

LP, LQ, UP, UQ, KN, KD = 176251, 111202, 301994, 190537, 10000000000, 6931471803


def cyc_ok(N, b):  # mirrors Collatz.cycCheck2
    return b == 0 or b * (UP * (3 * N) * KD + KN * UQ) <= (UQ * (3 * N) * KD) * (b * LP // LQ + 1)


def first_failing_b(N):
    b = 0
    while cyc_ok(N, b):
        b += 1
    return b


B_OLD = first_failing_b(N0)
B = first_failing_b(N)
E = B * LP // LQ + 1
assert 2 ** (E - 1) < 3 ** B, "E is not the least a with 3^B < 2^a"  # sanity only
# level of the coefficient stopping time result: j < J forces s < B when 2^(J-1) < 3^B
J = E
assert 2 ** (J - 1) < 3 ** B

# per-node cost from the plan
cost = []
maxsteps = 0
with open(args.plan) as fh:
    for line in fh:
        r, it, leaves, steps, mx = map(int, line.split())
        assert r == len(cost)
        cost.append(args.node_w + args.cert_w * it + args.m_w * (M1 - M0) * leaves + steps)
        maxsteps = max(maxsteps, mx)
assert len(cost) == R0, f"plan has {len(cost)} lines, expected 2^{J0}"
assert maxsteps <= FUEL, f"max steps {maxsteps} exceeds fuel {FUEL}"
total = sum(cost)

# greedy chunking: close a chunk when adding the next node would exceed the target
bounds = [0]
acc = 0
for r in range(R0):
    if acc > 0 and acc + cost[r] > args.cost:
        bounds.append(r)
        acc = 0
    acc += cost[r]
bounds.append(R0)
chunk_costs = [sum(cost[bounds[i]:bounds[i + 1]]) for i in range(len(bounds) - 1)]

os.makedirs(args.outdir, exist_ok=True)
only = set(args.only.split(",")) if args.only else None


def write(name, text):
    if only is None or name in only:
        with open(os.path.join(args.outdir, name + ".lean"), "w") as fh:
            fh.write(text)


HEADER = ("import Collatz.ExtDefs\n\n/-! Generated by scripts/gen_ext.py. Do not edit. -/\n\n")
HEADER_CYC = "import Collatz.Defs\n\n/-! Generated by scripts/gen_ext.py. Do not edit. -/\n\n"
EXT = f"resExt {J0} {D} {M0} {M1} {FUEL}"
CYC = f"cycCheck2 {N}"
RW, CW = (4, 3)

names = []
for i in range(len(bounds) - 1):
    lo, hi = bounds[i], bounds[i + 1]
    name = f"Ext{i:0{RW}d}"
    names.append(name)
    write(name, HEADER + f"theorem CollatzBig.ext{i:0{RW}d} : Collatz.kallFrom (Collatz.{EXT}) "
          f"{lo} {hi - lo} = true := by\n  decide +kernel\n")

CC = args.cyc_chunks
cb = [B * i // CC for i in range(CC)] + [B]
for i in range(CC):
    lo, hi = cb[i], cb[i + 1]
    name = f"ExtCyc{i:0{CW}d}"
    names.append(name)
    write(name, HEADER_CYC + f"theorem CollatzBig.extCyc{i:0{CW}d} : Collatz.kallFrom "
          f"(Collatz.{CYC}) {lo} {hi - lo} = true := by\n  decide +kernel\n")


def tree(tag, prefix, bnds, fn, w):
    """Balanced binary tree of small, explicitly typed `kallFrom_append` theorems."""
    decls = []

    def go(i, j):
        if j - i == 1:
            return f"CollatzBig.{prefix}{i:0{w}d}"
        mid = (i + j) // 2
        a, b = go(i, mid), go(mid, j)
        lo, l1, l2 = bnds[i], bnds[mid] - bnds[i], bnds[j] - bnds[mid]
        name = f"{tag}_{i}_{j}"
        decls.append(f"theorem {name} : kallFrom ({fn}) {lo} {l1 + l2} = true :=\n"
                     f"  kallFrom_append (f := {fn}) (lo := {lo}) (l1 := {l1}) (l2 := {l2})"
                     f" {a} {b}\n")
        return name
    root = go(0, len(bnds) - 1)
    return "\n".join(decls), root


ext_decls, ext_root = tree("extT", "ext", bounds, EXT, RW)
cyc_decls, cyc_root = tree("extCycT", "extCyc", cb, CYC, CW)

if only is None or "Ext" in only:
    with open(os.path.join(args.outdir, "Ext.lean"), "w") as fh:
        fh.write("import CollatzBig.CoeffStop\nimport Collatz.ExtKernel\n"
                 + "".join(f"import CollatzBig.{n}\n" for n in names))
        fh.write(f"""
/-!
# Extension of the large verification (generated by scripts/gen_ext.py)

The chunks of `CollatzBig.All` prove descent of every `2 ≤ n < {N0}` (`= 2^{K} * {M0}`).
The chunks `Ext*` extend this to every `2 ≤ n < {N}` (`= 2^{K} * {M1}`) with the sieve
`resExt` (`Collatz.ExtDefs`, soundness in `Collatz.ExtKernel`), and `ExtCyc*` check
`cycCheck2 {N} b` for `b < {B}`. Hence every cycle not containing `1` has at least `{B}` odd
and `{E}` even steps, and length at least `{B + E}`.
-/

namespace CollatzBig.Ext

open Collatz Finset

{ext_decls}
theorem extAll : kallFrom ({EXT}) 0 {R0} = true := {ext_root}

theorem descends_below : ∀ n, 2 ≤ n → n < {N} → Descends n := by
  have h := descends_of_resExt (k := {K}) (j0 := {J0}) (d := {D}) (M0 := {M0}) (M1 := {M1})
    (fuel := {FUEL}) rfl (by norm_num)
    (fun r hr => kall_of_kallFrom CollatzBig.resAll r (by norm_num at hr ⊢; omega))
    (fun r hr => kall_of_kallFrom CollatzBig.Ext.extAll r (by norm_num at hr ⊢; omega))
  intro n h2 hn
  exact h n h2 (by norm_num; omega)

theorem reachesOne_below : ∀ n, 1 ≤ n → n < {N} → ReachesOne n := by
  intro n h1 hn
  exact reachesOne_of_descends_below {N - 1}
    (fun m hm hm' => CollatzBig.Ext.descends_below m hm (by omega)) n h1 (by omega)

{cyc_decls}
theorem cycAll : kallFrom ({CYC}) 0 {B} = true := {cyc_root}

/-- Any cycle not containing `1` has at least `{B}` odd steps. -/
theorem odds_card_ge {{n p : ℕ}} (hc : IsCycle n p) (hnr : ¬ ReachesOne n) :
    {B} ≤ (odds n p).card :=
  odds_card_ge_of_check2 hc hnr (by norm_num) CollatzBig.Ext.reachesOne_below
    (kall_of_kallFrom_zero CollatzBig.Ext.cycAll)

/-- Any cycle not containing `1` has at least `{E}` even steps. -/
theorem evens_card_ge {{n p : ℕ}} (hc : IsCycle n p) (hnr : ¬ ReachesOne n) :
    {E} ≤ (evens n p).card := by
  have hb := CollatzBig.Ext.odds_card_ge hc hnr
  have h := lower_exp (by omega) (three_pow_lt_two_pow hc)
  unfold LP LQ at h
  omega

/-- Any cycle not containing `1` has length at least `{B + E}`. -/
theorem cycle_length_ge {{n p : ℕ}} (hc : IsCycle n p) (hnr : ¬ ReachesOne n) :
    {B + E} ≤ p := by
  have h1 := CollatzBig.Ext.odds_card_ge hc hnr
  have h2 := CollatzBig.Ext.evens_card_ge hc hnr
  have := card_evens_add_card_odds n p
  omega

/-- A positive integer that is a periodic point of `T` and does not reach `1` has period at
least `{E}`. -/
theorem kstepT_period_ge {{n p : ℕ}} (hn : 1 ≤ n) (hp : 1 ≤ p) (h : kstepT^[p] n = n)
    (hnr : ¬ ReachesOne n) : {E} ≤ p :=
  Collatz.kstepT_period_ge (fun _ _ hc hr => CollatzBig.Ext.evens_card_ge hc hr) hn hp h hnr

theorem natCast_periodic_ge {{n p : ℕ}} (hn : 1 ≤ n) (hp : 1 ≤ p)
    (h : TwoAdic.T^[p] (n : ℤ_[2]) = n) (hnr : ¬ ReachesOne n) : {E} ≤ p :=
  natCast_periodic_ge_of (fun _ _ hc hr => CollatzBig.Ext.evens_card_ge hc hr) hn hp h hnr

lemma pow_bound_large : 2 ^ {J - 1} < 3 ^ {B} := by decide +kernel

/-- **Coefficient stopping time conjecture up to level {J - 1}.** -/
theorem stops_at_coeff_stop {{n j : ℕ}} (hn : 2 ≤ n) (hj : 1 ≤ j) (hJ : j < {J})
    (h : 3 ^ oddCount j n < 2 ^ j) : ∃ i, 1 ≤ i ∧ i ≤ j ∧ kstepT^[i] n < n := by
  have hmid := kstepT_descends_of_resExt (k := {K}) (j0 := {J0}) (d := {D}) (M0 := {M0})
    (M1 := {M1}) (fuel := {FUEL}) rfl (by norm_num)
    (fun r hr => kall_of_kallFrom CollatzBig.resAll r (by norm_num at hr ⊢; omega))
    (fun r hr => kall_of_kallFrom CollatzBig.Ext.extAll r (by norm_num at hr ⊢; omega))
  refine cst_of_tables (fuel := 1000) (F := {max(FUEL, 2 * K + 1)}) (N0 := 131072) (N1 := {N})
    (B0 := 971) (B1 := {B}) (by norm_num) (by norm_num)
    (fun n h2 hlt => kallFrom_spec CollatzBig.cstSmall n (by omega) (by omega))
    (fun n h2 hlt => by
      obtain ⟨i, hi, hiF, hd⟩ := hmid n h2 (by norm_num; omega)
      exact ⟨i, hi, by simpa using hiF, hd⟩)
    CollatzBig.cyc17 (kall_of_kallFrom_zero CollatzBig.Ext.cycAll) ?_ hn hj h ?_
  · intro s j' h3 hj'
    have : 3 ^ s < 3 ^ 631 :=
      lt_of_lt_of_le h3 (le_trans (Nat.pow_le_pow_right (by norm_num) (by omega))
        CollatzBig.pow_bound_small.le)
    have := (Nat.pow_lt_pow_iff_right (by norm_num)).1 this
    omega
  · have : 3 ^ oddCount j n < 3 ^ {B} :=
      lt_of_lt_of_le h (le_trans (Nat.pow_le_pow_right (by norm_num) (by omega))
        CollatzBig.Ext.pow_bound_large.le)
    exact (Nat.pow_lt_pow_iff_right (by norm_num)).1 this

/-- **Terras' periodicity without exceptions** for `k < {J}`. -/
theorem stopsBy_iff_goodSet {{k n : ℕ}} (hk : k < {J}) (hn : 2 ≤ n) :
    (∃ j ∈ Icc 1 k, kstepT^[j] n < n) ↔ n % 2 ^ k ∈ goodSet k := by
  constructor
  · rintro ⟨j, hj, hd⟩
    rw [mem_Icc] at hj
    simp only [goodSet, mem_filter, mem_range]
    exact ⟨Nat.mod_lt _ (by positivity), j, mem_Icc.2 hj, stopsBy_imp hj.2 hd⟩
  · intro hg
    simp only [goodSet, mem_filter, mem_range] at hg
    obtain ⟨-, j, hj, h3⟩ := hg
    rw [mem_Icc] at hj
    rw [← oddCount_mod hj.2] at h3
    obtain ⟨i, hi, hij, hd⟩ := CollatzBig.Ext.stops_at_coeff_stop hn hj.1 (by omega) h3
    exact ⟨i, mem_Icc.2 ⟨hi, by omega⟩, hd⟩

end CollatzBig.Ext
""")

if only is None or "ExtAudit" in only:
    thms = ["descends_below", "cycle_length_ge", "kstepT_period_ge", "natCast_periodic_ge",
            "stops_at_coeff_stop", "stopsBy_iff_goodSet"]
    with open(os.path.join(args.outdir, "ExtAudit.lean"), "w") as fh:
        fh.write("import CollatzBig.Ext\n\n/-! Axiom check for the extension (generated by "
                 "scripts/gen_ext.py). -/\n")
        for t in thms:
            fh.write(f"\n/-- info: 'CollatzBig.Ext.{t}' depends on axioms: [propext, "
                     f"Classical.choice, Quot.sound] -/\n#guard_msgs in #print axioms "
                     f"CollatzBig.Ext.{t}\n")

if only is None:
    with open(os.path.join(args.outdir, "ext_queue.txt"), "w") as fh:
        fh.write("".join(n + "\n" for n in names))

print(f"N0={N0} N={N} B_old={B_OLD} B={B} E={E} length>={B + E} coeff-stop level<{J}")
print(f"residue chunks={len(bounds) - 1} cycle chunks={CC} total cost={total} "
      f"chunk cost max={max(chunk_costs)} min={min(chunk_costs)} max node cost={max(cost)} "
      f"max steps={maxsteps}")
