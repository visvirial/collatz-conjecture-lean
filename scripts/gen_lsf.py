#!/usr/bin/env python3
"""Generate a run-checked instance of Collatz/LongStopFast.lean (potential mod 3^J, ratio P/Q).

Usage (from the repository root):
    gen_lsf.py HFILE J P Q W S CHUNK [OUTROOT]
HFILE lists h(0), ..., h(3^J - 1), one per line (scripts/longstop_pot.c, or
scripts/longstop_pot_omp.c, writes it). W = bits per entry (needs max h < 2^W), S = entries per
piece (a multiple of 3; S * W bits per literal, keep S * W <= ~50000), CHUNK = steps q per
chunk module (each step checks the two sources s = 3q + 1, 3q + 2).

Writes (under OUTROOT, default "."):
    Collatz/LS<J>/P###.lean     the pieces of the potential (one block of pieces per module),
    Collatz/LS<J>/Defs.lean     the piece lookup `pc`,
    Collatz/LS<J>/C###.lean     the kernel-checked chunks (`runsOk ... = true` by decide +kernel),
    Collatz/LongStop<J>.lean    the combination and the main theorem (`long_stopping_log_fifteen` for J = 15).
The run decomposition: consecutive sources s whose lookups (h(s), h(2s % M), and, where the even
move fails, the three odd targets) stay in the same pieces form one run.
"""
import sys, os
sys.set_int_max_str_digits(0)

hfile, J, P, Q, W, S, CH = sys.argv[1], *map(int, sys.argv[2:8])
root = sys.argv[8] if len(sys.argv) > 8 else "."
M = 3 ** J
ns = f"Collatz.LS{J}"
d = f"{root}/Collatz/LS{J}"
os.makedirs(d, exist_ok=True)
h = [int(x) for x in open(hfile)]
assert len(h) == M
H = max(h)
assert H < 2 ** W, (H, W)
NP = -(-M // S)

assert S % 3 == 0
NQ = M // 3

# certificate condition (independent re-check) and run decomposition, in steps q (s = 3q+1, 3q+2)
def needs(q):
    """Piece indices needed at q: (a, b1, b2, c0, c1, c2), None = not needed."""
    s1, s2 = 3 * q + 1, 3 * q + 2
    a = s1 // S
    assert s2 // S == a
    e1, e2 = 2 * s1 % M, 2 * s2 % M
    assert h[s1] + P <= h[e1], s1  # s1 = 1 (mod 3) has no odd move
    if h[s2] + P <= h[e2]:
        return (a, e1 // S, e2 // S, None, None, None)
    assert s2 % 9 in (2, 8), s2
    os_ = [(2 * (s2 + k * M) - 1) // 3 % M for k in range(3)]
    assert all(h[s2] + P <= h[o] + Q for o in os_), s2
    return (a, e1 // S, None) + tuple(o // S for o in os_)

GEN = "/-! Generated by scripts/gen_lsf.py. Do not edit. -/\n\n"
chunks = []  # (lo, len, runs) in q units
lo = 0
while lo < NQ:
    hi = min(NQ, lo + CH)
    runs = []
    cur, start = [None] * 6, lo
    for q in range(lo, hi):
        nd = needs(q)
        if all(x is None or y is None or x == y for x, y in zip(cur, nd)):
            cur = [x if x is not None else y for x, y in zip(cur, nd)]
        else:
            runs.append((q - start, *[0 if x is None else x for x in cur]))
            cur, start = list(nd), q
    runs.append((hi - start, *[0 if x is None else x for x in cur]))
    chunks.append((lo, hi - lo, runs))
    lo = hi

K = 1
while K * K < NP:
    K += 1
NB = -(-NP // K)
for j in range(NB):  # block j (pieces jK .. jK + K - 1) in its own module P###
    with open(f"{d}/P{j:03d}.lean", "w") as f:
        f.write("/-! Generated by scripts/gen_lsf.py. Do not edit. -/\n\n" + f"namespace {ns}\n\n")
        idx = range(j * K, min(NP, (j + 1) * K))
        for i in idx:
            B = 0
            for r in reversed(range(i * S, min(M, (i + 1) * S))):
                B = (B << W) | h[r]
            f.write(f"def piece{i} : Nat := {B}\n")
        f.write(f"\ndef block{j} : List Nat := [" + ", ".join(f"piece{i}" for i in idx) + "]\n\n")
        f.write(f"end {ns}\n")
with open(f"{d}/Defs.lean", "w") as f:
    f.write("import Collatz.LSF.Basic\n" + "".join(f"import Collatz.LS{J}.P{j:03d}\n" for j in range(NB)) +
            "\n/-!\nGenerated by scripts/gen_lsf.py. Do not edit.\n\n"
            f"The potential mod `3^{J}` (ratio `{P}/{Q}`, values `≤ {H}`) for `Collatz.LongStop{J}`, in\n"
            f"{NP} pieces of {S} residues with {W} bits each, {K} pieces per block module\n"
            f"`Collatz/LS{J}/P*.lean` (no Mathlib).\n-/\n\nnamespace {ns}\n\n")
    f.write("def blocks : List (List Nat) := [" + ", ".join(f"block{j}" for j in range(NB)) + "]\n\n")
    f.write(f"/-- Piece `i` of the potential (two-level lookup, {K} pieces per block). -/\n"
            f"def pc (i : Nat) : Nat := (blocks.getD (i / {K}) []).getD (i % {K}) 0\n\n"
            f"end {ns}\n")

for c, (lo, ln, runs) in enumerate(chunks):
    with open(f"{d}/C{c:03d}.lean", "w") as f:
        f.write(f"import Collatz.LS{J}.Defs\n\n" + GEN + f"namespace {ns}\n\n")
        f.write(f"def runs{c:03d} : List Collatz.LSF.Run :=\n  [" +
                ",\n   ".join("(" + ", ".join(map(str, r)) + ")" for r in runs) + "]\n\n")
        f.write(f"theorem chunk{c:03d} :\n    Collatz.LSF.runsOk pc {S} {W} {M} {P} {Q} runs{c:03d} {lo} = true := by\n"
                "  decide +kernel\n\n")
        f.write(f"theorem len{c:03d} : Collatz.LSF.runsLen runs{c:03d} = {ln} := by decide +kernel\n\n")
        f.write(f"end {ns}\n")

nch = len(chunks)
WORD = {13: "thirteen", 14: "fourteen", 15: "fifteen", 16: "sixteen"}.get(J, f"mod{J}")
gam = 1 / (0.6931471805599453 - P / Q * 1.0986122886681098)
Hb = 2 ** W - 1
with open(f"{root}/Collatz/LongStop{J}.lean", "w") as f:
    f.write("\n".join(f"import Collatz.LS{J}.C{c:03d}" for c in range(nch)) +
            "\nimport Collatz.LongStopFast\n\n")
    f.write(f"""/-!
# Long trajectories mod `3^{J}` with run-based kernel checks: `γ ≈ {gam:.3f}`

Generated by `scripts/gen_lsf.py`. The instance of `Collatz.LongStopGen` with `M = 3^{J}`,
`P/Q = {P}/{Q}` and `H = {Hb}`: the potential is stored in `Collatz/LS{J}/P*.lean` and the
certificate condition is checked per source residue on runs by `decide +kernel` in the {nch}
modules `Collatz/LS{J}/C*.lean` (`Collatz.LongStopFast`). Infinitely many `n` reach `1` only after
`σ(n) ≥ γ log n - c` steps, `γ = 1 / (log 2 - ({P}/{Q}) log 3) ≈ {gam:.4f}`.
-/

namespace {ns}

open Collatz.LSF in
theorem good : ∀ s < {M}, Good (pot pc {S} {W}) {M} {P} {Q} s := by
  intro s hs
""")
    for c, (lo, ln, runs) in enumerate(chunks):
        g = f"runsOk_spec chunk{c:03d} s (by omega) (by rw [len{c:03d}]; omega)"
        if c < nch - 1:
            f.write(f"  rcases Nat.lt_or_ge s {3 * (lo + ln)} with h | h\n  · exact {g}\n")
        else:
            f.write(f"  exact {g}\n")
    f.write(f"""
theorem cert : Collatz.LSCert (Collatz.LSF.pot pc {S} {W}) {M} {P} {Q} :=
  Collatz.LSF.lsCert_of_good (by norm_num) good

end {ns}

namespace Collatz

/-- **Infinitely many `n` need at least `≈ {gam:.3f} log n` steps to reach `1`**:
`{Q} log n - {2 * P + Hb} log 3 ≤ ({Q} log 2 - {P} log 3) σ(n)` with `σ(n) = L + 2` for every `L`. -/
theorem long_stopping_log_{WORD} (L : ℕ) : ∃ n, 1 ≤ n ∧ kstepT^[L + 2] n = 1 ∧
    (∀ i < L + 2, kstepT^[i] n ≠ 1) ∧
    {Q} * Real.log n - {2 * P + Hb} * Real.log 3 ≤ ({Q} * Real.log 2 - {P} * Real.log 3) * (L + 2 : ℕ) := by
  obtain ⟨n, h1, h2, h3, h4⟩ := long_stopping_log_gen (M := {M}) (P := {P}) (Q := {Q}) (H := {Hb})
    (by norm_num) (by norm_num) LS{J}.cert
    (fun r _ => by have := LSF.pot_lt LS{J}.pc {S} {W} r; norm_num at this; omega) L
  refine ⟨n, h1, h2, h3, ?_⟩
  norm_num at h4 ⊢
  linarith

end Collatz
""")
print("H", H, "pieces", NP, "blocks", NB, "chunks", nch, "runs", sum(len(r) for _, _, r in chunks),
      "max runs/chunk", max(len(r) for _, _, r in chunks))
