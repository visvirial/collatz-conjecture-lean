#!/usr/bin/env python3
"""Generate the CollatzBig library: chunked kernel verifications of
  * descent of every 2 <= n < N = 2^K * M (via `resCheck K M FUEL r`, r < 2^K), and
  * the cycle exponent check `cycCheck2 N b` for b < B,
then the combined theorems in CollatzBig/All.lean.

Usage: gen_big.py K M FUEL RES_CHUNKS CYC_CHUNKS plan.txt
B is computed as the first b for which cycCheck2 N b fails.
plan.txt is the stdout of scripts/plan.c (`r steps maxsteps` per survivor residue),
used to balance chunk costs.
"""
import os
import sys

K, M, FUEL, RC, CC = map(int, sys.argv[1:6])
plan_file = sys.argv[6]
R = 2 ** K
N = R * M


LP, LQ, UP, UQ, KN, KD = 176251, 111202, 301994, 190537, 10000000000, 6931471803


def first_failing_b(N):
    # mirrors Collatz.cycCheck2
    b = 0
    while True:
        b += 1
        if not (b * (UP * (3 * N) * KD + KN * UQ) <= (UQ * (3 * N) * KD) * (b * LP // LQ + 1)):
            return b


B = first_failing_b(N)
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
outdir = os.path.join(root, "CollatzBig")
os.makedirs(outdir, exist_ok=True)
# remove only generated files (Bridge, CoeffStop, Cst*, Audit are hand-written)
for f in os.listdir(outdir):
    if f.endswith(".lean") and (f.startswith("Res") or f.startswith("Cyc") or f == "All.lean"):
        os.remove(os.path.join(outdir, f))

# per-residue cost: survivors from plan, plus a small constant for the certificate
cost = [40] * R
with open(plan_file) as fh:
    for line in fh:
        r, steps, _ = map(int, line.split())
        cost[r] += steps + 20 * M
total = sum(cost)

# balanced residue boundaries
bounds = [0]
acc = 0
for r in range(R):
    acc += cost[r]
    if acc >= total * len(bounds) / RC and len(bounds) < RC:
        bounds.append(r + 1)
if bounds[-1] != R:
    bounds.append(R)

HEADER = "import Collatz.Defs\n\n/-! Generated by scripts/gen_big.py. Do not edit. -/\n\n"
RES = f"resCheck {K} {M} {FUEL}"
CYC = f"cycCheck2 {N}"

names = []
for i in range(len(bounds) - 1):
    lo, hi = bounds[i], bounds[i + 1]
    name = f"Res{i:04d}"
    names.append(name)
    with open(os.path.join(outdir, name + ".lean"), "w") as fh:
        fh.write(HEADER)
        fh.write(f"theorem CollatzBig.res{i:04d} : Collatz.kallFrom (Collatz.{RES}) {lo} {hi - lo}"
                 f" = true := by\n  decide +kernel\n")

# cycle chunks: uniform cost per b
cb = [B * i // CC for i in range(CC)] + [B]
for i in range(len(cb) - 1):
    lo, hi = cb[i], cb[i + 1]
    name = f"Cyc{i:03d}"
    names.append(name)
    with open(os.path.join(outdir, name + ".lean"), "w") as fh:
        fh.write(HEADER)
        fh.write(f"theorem CollatzBig.cyc{i:03d} : Collatz.kallFrom (Collatz.{CYC}) {lo} {hi - lo}"
                 f" = true := by\n  decide +kernel\n")


def tree(tag, prefix, bnds, fn, w):
    """Combine chunk theorems in a balanced binary tree of small, explicitly typed theorems.

    A linear chain of `have`s accumulates unevaluated sums in the types and becomes
    super-linear for thousands of chunks; here every node states literal bounds.
    Returns (declarations, name of the root theorem).
    """
    decls = []
    def go(i, j):  # chunks i .. j-1
        if j - i == 1:
            return f"CollatzBig.{prefix}{i:{w}}"
        mid = (i + j) // 2
        a, b = go(i, mid), go(mid, j)
        lo, l1, l2 = bnds[i], bnds[mid] - bnds[i], bnds[j] - bnds[mid]
        name = f"{tag}_{i}_{j}"
        decls.append(f"theorem {name} : kallFrom ({fn}) {lo} {l1 + l2} = true :=\n"
                     f"  kallFrom_append (f := {fn}) (lo := {lo}) (l1 := {l1}) (l2 := {l2})"
                     f" {a} {b}\n")
        return name
    root = go(0, len(bnds) - 1)
    return "\n".join(decls), root


E = B * 176251 // 111202 + 1  # LP / LQ, see Collatz.Defs
res_decls, res_root = tree("resT", "res", bounds, RES, "04d")
cyc_decls, cyc_root = tree("cycT", "cyc", cb, CYC, "03d")

with open(os.path.join(outdir, "All.lean"), "w") as fh:
    fh.write("import Collatz.CycleBound\n" + "".join(f"import CollatzBig.{n}\n" for n in names))
    fh.write(f"""
/-!
# Large verification (generated by scripts/gen_big.py)

Every `2 ≤ n < {N}` (`= 2^{K} * {M}`) descends, and therefore every cycle not
containing `1` has at least `{B}` odd steps.
-/

namespace CollatzBig

open Collatz

{res_decls}
theorem resAll : kallFrom ({RES}) 0 {R} = true := {res_root}

theorem descends_below : ∀ n, 2 ≤ n → n < {N} → Descends n := by
  have h := descends_of_resCheck (k := {K}) (M := {M}) (fuel := {FUEL})
    (fun r hr => kall_of_kallFrom resAll r (by norm_num at hr ⊢; omega))
  intro n h2 hn
  exact h n h2 (by norm_num; omega)

theorem reachesOne_below : ∀ n, 1 ≤ n → n < {N} → ReachesOne n := by
  intro n h1 hn
  exact reachesOne_of_descends_below {N - 1} (fun m hm hm' => descends_below m hm (by omega))
    n h1 (by omega)

{cyc_decls}
theorem cycAll : kallFrom ({CYC}) 0 {B} = true := {cyc_root}

/-- Any cycle not containing `1` has at least `{B}` odd steps. -/
theorem odds_card_ge {{n p : ℕ}} (hc : IsCycle n p) (hnr : ¬ ReachesOne n) :
    {B} ≤ (odds n p).card :=
  odds_card_ge_of_check2 hc hnr (by norm_num) reachesOne_below (kall_of_kallFrom_zero cycAll)

/-- Any cycle not containing `1` has at least `{E}` even steps
(from `2^LP < 3^LQ` and `3^b < 2^a`; avoids evaluating `Nat.log2 (3^B)` in the kernel). -/
theorem evens_card_ge {{n p : ℕ}} (hc : IsCycle n p) (hnr : ¬ ReachesOne n) :
    {E} ≤ (evens n p).card := by
  have hb := odds_card_ge hc hnr
  have h := lower_exp (by omega) (three_pow_lt_two_pow hc)
  unfold LP LQ at h
  omega

/-- Any cycle not containing `1` has length at least `{B + E}`. -/
theorem cycle_length_ge {{n p : ℕ}} (hc : IsCycle n p) (hnr : ¬ ReachesOne n) :
    {B + E} ≤ p := by
  have h1 := odds_card_ge hc hnr
  have h2 := evens_card_ge hc hnr
  have := card_evens_add_card_odds n p
  omega

end CollatzBig
""")


print(f"N={N} residue chunks={len(bounds)-1} cycle chunks={len(cb)-1} B={B}")
