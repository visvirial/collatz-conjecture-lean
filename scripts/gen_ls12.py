#!/usr/bin/env python3
"""Generate the mod 3^12 instance of Collatz/LongStopGen.lean (gamma ~ 5.38).

Writes Collatz/LS12/Defs.lean (the potential h on the residues mod 3^12, ratio 6/13, values <= 73,
in 81 pieces of 6561 residues with 7 bits each: one large literal would elaborate in quadratic
time), the kernel-checked chunks Collatz/LS12/C###.lean and Collatz/LS12/Bound.lean.

Usage: gen_ls12.py HFILE NCHUNKS, run from the repository root, where HFILE lists
h(0), ..., h(3^12 - 1), one per line (scripts/longstop_pot.c writes it: `./longstop_pot 12 6 13 HFILE`).
"""
import sys
sys.set_int_max_str_digits(0)
hfile, nch = sys.argv[1], int(sys.argv[2])
out = "Collatz/LS12"
J, P, Q, W, K = 12, 6, 13, 7, 81
M = 3 ** J; S = M // K
h = [int(x) for x in open(hfile)]
assert len(h) == M
assert all(t % 3 == 0 or h[t % M] + P <= h[2 * t % M] or
           (t % 9 in (2, 8) and h[t % M] + P <= h[(2 * t - 1) // 3 % M] + Q) for t in range(3 * M))
H = max(h); assert H == 73
GEN = "/-! Generated by scripts/gen_ls12.py. Do not edit. -/\n\n"
with open(f"{out}/Defs.lean", "w") as f:
    f.write("import Collatz.Defs\n\n/-!\nGenerated by scripts/gen_ls12.py. Do not edit.\n\n"
            "The potential mod `3^12` for `Collatz.LongStop12`, in 81 pieces of 6561 residues with 7 bits\n"
            "each, and the certificate condition as a `Bool` (no Mathlib, so that the chunk modules\n"
            "`Collatz/LS12/C*.lean` load quickly).\n-/\n\nnamespace Collatz.LS12\n\n")
    for i in range(K):
        B = 0
        for r in reversed(range(i * S, (i + 1) * S)):
            B = (B << W) | h[r]
        f.write(f"def piece{i} : Nat := {B}\n")
    f.write("\ndef pieces : List Nat := [" + ", ".join(f"piece{i}" for i in range(K)) + "]\n\n")
    f.write("/-- The potential: entry `r % 6561` of piece `r / 6561`. -/\n"
            "def pot (r : Nat) : Nat := (pieces.getD (r / 6561) 0 >>> (7 * (r % 6561))) % 128\n\n"
            "/-- The certificate condition of `Collatz.LSCert pot 531441 6 13` at `t`. -/\n"
            "def ok (t : Nat) : Bool :=\n"
            "  t % 3 == 0 || Nat.ble (pot (t % 531441) + 6) (pot (2 * t % 531441)) ||\n"
            "    ((t % 9 == 2 || t % 9 == 8) &&\n"
            "      Nat.ble (pot (t % 531441) + 6) (pot ((2 * t - 1) / 3 % 531441) + 13))\n\n"
            "end Collatz.LS12\n")
N = 3 * M
size = -(-N // nch)
for c in range(nch):
    lo = c * size; ln = min(size, N - lo)
    with open(f"{out}/C{c:03d}.lean", "w") as f:
        f.write("import Collatz.LS12.Defs\n\n" + GEN +
                f"theorem Collatz.LS12.chunk{c:03d} :\n    Collatz.kallFrom Collatz.LS12.ok {lo} {ln} = true := by\n  decide +kernel\n")
with open(f"{out}/Bound.lean", "w") as f:
    f.write("import Collatz.LS12.Defs\n\n" + GEN +
            "theorem Collatz.LS12.bound :\n    Collatz.kall (fun r => Nat.ble (Collatz.LS12.pot r) 73) 531441 = true := by\n  decide +kernel\n")
expr = "chunk000"
for c in range(1, nch):
    expr = f"(kallFrom_append {expr} chunk{c:03d})"
with open("Collatz/LongStop12.lean", "w") as f:
    f.write("\n".join(f"import Collatz.LS12.C{c:03d}" for c in range(nch)) + "\nimport Collatz.LS12.Bound\nimport Collatz.LongStopGen\n\n")
    f.write('''/-!
# Long trajectories mod `3^12`: `γ ≈ 5.38`

The instance of `Collatz.LongStopGen` with `M = 3^12`, `P/Q = 6/13` and `H = 73`
(`scripts/longstop_cert.py 12 6 13`, `scripts/gen_ls12.py`): the certificate condition is checked
by `decide +kernel` in the generated modules `Collatz/LS12/C*.lean`, which are combined here.
Infinitely many `n` reach `1` only after `σ(n) ≥ γ log n - c` steps,
`γ = 1 / (log 2 - (6/13) log 3) ≈ 5.38`.
-/

namespace Collatz.LS12

theorem all_ok : Collatz.kallFrom ok 0 1594323 = true := by
  have h := ''' + expr + '''
  norm_num at h
  exact h

theorem cert : LSCert pot 531441 6 13 := by
  intro t ht h3
  have := kallFrom_spec all_ok t (Nat.zero_le t) (by omega)
  simp only [ok, Bool.or_eq_true, Bool.and_eq_true, beq_iff_eq, Nat.ble_eq] at this
  omega

theorem pot_le : ∀ r < 531441, pot r ≤ 73 := by
  intro r hr
  simpa using kall_spec bound r hr

end Collatz.LS12

namespace Collatz

/-- **Infinitely many `n` need at least `≈ 5.38 log n` steps to reach `1`**:
`13 log n - 85 log 3 ≤ (13 log 2 - 6 log 3) σ(n)` with `σ(n) = L + 2` for every `L`. -/
theorem long_stopping_log_twelve (L : ℕ) : ∃ n, 1 ≤ n ∧ kstepT^[L + 2] n = 1 ∧
    (∀ i < L + 2, kstepT^[i] n ≠ 1) ∧
    13 * Real.log n - 85 * Real.log 3 ≤ (13 * Real.log 2 - 6 * Real.log 3) * (L + 2 : ℕ) := by
  obtain ⟨n, h1, h2, h3, h4⟩ := long_stopping_log_gen (M := 531441) (P := 6) (Q := 13) (H := 73)
    (by norm_num) (by norm_num) LS12.cert LS12.pot_le L
  refine ⟨n, h1, h2, h3, ?_⟩
  norm_num at h4 ⊢
  linarith

end Collatz
''')
print("H", H, "chunks", nch, "size", size)
